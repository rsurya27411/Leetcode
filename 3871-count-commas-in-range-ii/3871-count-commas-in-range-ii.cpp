class Solution {
public:
    long long countCommas(long long n) {
        long long ans=0;
        if(n >= 1000 && n < 1000000){
            ans=(n-1000) + 1;
        }
        if(n >= 1000000 && n < 1000000000){
            ans=((n-1000000)*2) + 2 + 999000;
        }
        if(n >= 1000000000 && n < 1000000000000){
            ans=((n-1000000000)*3) + 3 + 1998000000 + 999000;
        }
        if(n >= 1000000000000 && n <= 1000000000000000){
            ans=((n-1000000000000)*4) + 4 + 2997000000000 + 1998000000 + 999000;
        }
        if(n == 1000000000000000)
        ans++;
        return ans;
    }
};